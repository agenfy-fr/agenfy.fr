"use client";

import { useActionState, useState, useTransition } from "react";
import { Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Callout } from "@/components/shared/callout";
import { signOut } from "../actions";
import { startTotpEnrollment, verifyTotp, type EnrollResult, type VerifyState } from "./actions";

type Enrollment = Extract<EnrollResult, { factorId: string }>;

export function MfaForm({ factorId, next, required }: { factorId: string | null; next: string; required: boolean }) {
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [enrollError, setEnrollError] = useState<string | null>(null);
  const [enrolling, startEnrolling] = useTransition();
  const [state, verifyAction, verifying] = useActionState<VerifyState, FormData>(verifyTotp, null);

  const activeFactor = factorId ?? enrollment?.factorId ?? null;

  const enroll = () =>
    startEnrolling(async () => {
      setEnrollError(null);
      const result = await startTotpEnrollment();
      if ("error" in result) setEnrollError(result.error);
      else setEnrollment(result);
    });

  return (
    <div className="space-y-5">
      {!factorId && !enrollment && (
        <div className="space-y-4">
          <p className="text-sm text-muted-foreground">
            {required
              ? "La double authentification est obligatoire pour les comptes de l'équipe Agenfy."
              : "Protégez votre compte avec un code à usage unique en plus du mot de passe."}{" "}
            Installez une application d&apos;authentification (Google Authenticator, Microsoft Authenticator, 1Password,
            Bitwarden…), puis générez le QR code.
          </p>
          {enrollError && <Callout tone="destructive">{enrollError}</Callout>}
          <Button type="button" className="w-full" onClick={enroll} disabled={enrolling}>
            {enrolling && <Loader2 className="mr-2 h-4 w-4 animate-spin" aria-hidden="true" />}
            Générer le QR code
          </Button>
        </div>
      )}

      {enrollment && (
        <div className="space-y-3 text-center">
          <p className="text-sm text-muted-foreground">Scannez ce QR code avec votre application :</p>
          {/* eslint-disable-next-line @next/next/no-img-element -- SVG data URI generated by Supabase Auth */}
          <img src={enrollment.qrCode} alt="QR code de double authentification" width={180} height={180} className="mx-auto rounded-md bg-white p-2" />
          <details className="text-xs text-muted-foreground">
            <summary className="cursor-pointer">Impossible de scanner ? Saisir la clé manuellement</summary>
            <code className="mt-2 block break-all rounded bg-muted px-2 py-1 font-mono text-foreground">{enrollment.secret}</code>
          </details>
        </div>
      )}

      {activeFactor && (
        <form action={verifyAction} className="space-y-4">
          <input type="hidden" name="factorId" value={activeFactor} />
          <input type="hidden" name="next" value={next} />
          {state?.error && <Callout tone="destructive">{state.error}</Callout>}
          <div className="space-y-2">
            <Label htmlFor="code">Code à 6 chiffres</Label>
            <Input
              id="code"
              name="code"
              inputMode="numeric"
              autoComplete="one-time-code"
              pattern="[0-9 -]{6,7}"
              maxLength={7}
              required
              autoFocus
              className="text-center font-mono text-lg tracking-[0.3em]"
            />
          </div>
          <Button type="submit" className="w-full" disabled={verifying}>
            {verifying && <Loader2 className="mr-2 h-4 w-4 animate-spin" aria-hidden="true" />}
            {enrollment ? "Activer la double authentification" : "Vérifier"}
          </Button>
        </form>
      )}

      <form action={signOut}>
        <button type="submit" className="w-full text-center text-xs text-muted-foreground hover:text-foreground hover:underline">
          Se déconnecter
        </button>
      </form>
    </div>
  );
}
